CREATE OR REPLACE FUNCTION public.reorder_video_categories (
  p_roadmap_id uuid,
  p_ids        uuid[]
)
  RETURNS integer
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
DECLARE
  v_owner uuid;
  v_count integer := 0;
BEGIN
  SELECT user_id INTO v_owner FROM public.user_roadmaps WHERE id = p_roadmap_id;
  IF v_owner IS NULL OR v_owner <> auth.uid() THEN
    RAISE EXCEPTION 'roadmap not found';
  END IF;
  WITH ord AS (
    SELECT id, (ordinality - 1) * 10 AS sort_order FROM unnest(p_ids) WITH ORDINALITY AS t(id, ordinality)
  ), upd AS (
    UPDATE public.video_categories c
    SET sort_order = ord.sort_order, updated_at = timezone('utc'::text, now())
    FROM ord
    WHERE c.id = ord.id AND c.roadmap_id = p_roadmap_id
    RETURNING 1
  )
  SELECT count(*) INTO v_count FROM upd;
  RETURN v_count;
END;
$function$;

CREATE OR REPLACE FUNCTION public.requeue_stale_analysis_jobs (
  p_stale_after  interval DEFAULT '00:15:00'::interval,
  p_max_attempts integer  DEFAULT 3
)
  RETURNS integer
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
DECLARE
  v_requeued integer := 0;
  v_failed integer := 0;
BEGIN
  WITH f AS (
    UPDATE public.analysis_jobs
    SET status = 'failed', finished_at = timezone('utc'::text, now()),
        error = coalesce(error, '') || ' [gave up after ' || attempts || ' attempts]'
    WHERE status = 'processing' AND started_at < timezone('utc'::text, now()) - p_stale_after
      AND attempts >= p_max_attempts
    RETURNING video_upload_id
  )
  UPDATE public.video_uploads v SET analysis_status = 'failed', updated_at = timezone('utc'::text, now())
  FROM f WHERE v.id = f.video_upload_id;
  GET DIAGNOSTICS v_failed = ROW_COUNT;

  UPDATE public.analysis_jobs
  SET status = 'queued', worker_id = NULL, started_at = NULL
  WHERE status = 'processing' AND started_at < timezone('utc'::text, now()) - p_stale_after
    AND attempts < p_max_attempts;
  GET DIAGNOSTICS v_requeued = ROW_COUNT;
  RETURN v_requeued + v_failed;
END;
$function$;


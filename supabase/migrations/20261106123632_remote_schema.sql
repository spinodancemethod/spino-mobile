  SET category_id = p_category_id,
      updated_at = timezone('utc'::text, now())
  WHERE id = snippet_row.promoted_segment_id
    AND user_id = current_user_id
    AND video_upload_id = snippet_row.video_upload_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Linked roadmap segment was not found.' USING ERRCODE = 'P0002';
  END IF;

  RETURN snippet_row.promoted_segment_id;
END;
$function$;


      AND roadmap_id = video_roadmap_id
      AND (system_category = true OR user_id = current_user_id)
  ) THEN
    RAISE EXCEPTION 'Category does not belong to the source video roadmap.' USING ERRCODE = '23514';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.dance_positions
    WHERE id = p_final_position_id AND active = true
  ) THEN
    RAISE EXCEPTION 'Selected dance position is not active.' USING ERRCODE = '23514';
  END IF;

  UPDATE public.generated_snippets
  SET final_position_id = p_final_position_id,
      is_manually_corrected = true,

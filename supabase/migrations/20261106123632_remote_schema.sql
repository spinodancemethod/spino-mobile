CREATE OR REPLACE FUNCTION public.claim_next_video_analysis_job (
  p_worker_id text
)
  RETURNS SETOF public.video_analysis_jobs
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
BEGIN
  RETURN QUERY
  WITH next_job AS (
    SELECT jobs.id
    FROM public.video_analysis_jobs AS jobs
    WHERE jobs.status = 'queued'
      OR (jobs.status = 'processing' AND (jobs.worker_heartbeat_at IS NULL OR jobs.worker_heartbeat_at < timezone('utc'::text, now()) - interval '30 minutes'))
    ORDER BY jobs.created_at
    FOR UPDATE SKIP LOCKED
    LIMIT 1
  )
  UPDATE public.video_analysis_jobs AS jobs
  SET status = 'processing',
      stage = 'media_validation',
      worker_id = p_worker_id,
      worker_heartbeat_at = timezone('utc'::text, now()),
      started_at = COALESCE(jobs.started_at, timezone('utc'::text, now())),
      completed_at = NULL,
      error_message = NULL,
      retry_count = CASE WHEN jobs.status = 'processing' THEN jobs.retry_count + 1 ELSE jobs.retry_count END,
      updated_at = timezone('utc'::text, now())
  FROM next_job
  WHERE jobs.id = next_job.id
  RETURNING jobs.*;
END;
$function$;


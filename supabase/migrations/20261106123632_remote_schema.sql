CREATE OR REPLACE FUNCTION public.promote_generated_snippet (
  p_snippet_id          uuid,
  p_category_id         uuid,
  p_thumbnail_reference text DEFAULT NULL::text
)
  RETURNS uuid
  LANGUAGE plpgsql
  SET search_path TO 'public'
  AS $function$
DECLARE
  current_user_id uuid := auth.uid();
  snippet_row public.generated_snippets%ROWTYPE;
  video_roadmap_id uuid;
  created_segment_id uuid;
BEGIN
  IF current_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication is required.' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO snippet_row
  FROM public.generated_snippets
  WHERE id = p_snippet_id AND user_id = current_user_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Generated snippet was not found.' USING ERRCODE = 'P0002';
  END IF;

  IF snippet_row.promoted_segment_id IS NOT NULL THEN
    RETURN snippet_row.promoted_segment_id;
  END IF;

  SELECT roadmap_id INTO video_roadmap_id
  FROM public.video_uploads
  WHERE id = snippet_row.video_upload_id AND user_id = current_user_id;

  IF video_roadmap_id IS NULL THEN
    RAISE EXCEPTION 'Source video was not found.' USING ERRCODE = 'P0002';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.video_categories
    WHERE id = p_category_id
      AND roadmap_id = video_roadmap_id
      AND (system_category = true OR user_id = current_user_id)
  ) THEN
    RAISE EXCEPTION 'Category does not belong to the source video roadmap.' USING ERRCODE = '23514';
  END IF;

  INSERT INTO public.segments (user_id, video_upload_id, start_time, end_time, category_id, ai_confidence, ai_generated, user_confirmed, thumbnail_reference)
  VALUES (current_user_id, snippet_row.video_upload_id, snippet_row.start_timestamp, snippet_row.end_timestamp, p_category_id, snippet_row.detection_confidence, true, true, p_thumbnail_reference)
  RETURNING id INTO created_segment_id;

  UPDATE public.generated_snippets
  SET promoted_segment_id = created_segment_id, updated_at = timezone('utc'::text, now())
  WHERE id = snippet_row.id;

  RETURN created_segment_id;
END;
$function$;


CREATE OR REPLACE FUNCTION public.update_promoted_generated_snippet (
  p_snippet_id        uuid,
  p_final_position_id uuid,
  p_category_id       uuid
)
  RETURNS uuid
  LANGUAGE plpgsql
  SET search_path TO 'public'
  AS $function$
DECLARE
  current_user_id uuid := auth.uid();
  snippet_row public.generated_snippets%ROWTYPE;
  video_roadmap_id uuid;
BEGIN
  IF current_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication is required.' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO snippet_row
  FROM public.generated_snippets
  WHERE id = p_snippet_id AND user_id = current_user_id
  FOR UPDATE;

  IF NOT FOUND OR snippet_row.promoted_segment_id IS NULL THEN
    RAISE EXCEPTION 'Promoted generated snippet was not found.' USING ERRCODE = 'P0002';
  END IF;

  SELECT roadmap_id INTO video_roadmap_id
  FROM public.video_uploads
  WHERE id = snippet_row.video_upload_id AND user_id = current_user_id;


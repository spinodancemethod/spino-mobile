      FROM public.subscriptions s
      WHERE s.user_id = p_user_id
        AND s.status IN ('trialing', 'active', 'grace_period')
        AND (s.current_period_end IS NULL OR s.current_period_end > now())
    )
    WHEN auth.uid() = p_user_id THEN EXISTS (
      SELECT 1
      FROM public.subscriptions s
      WHERE s.user_id = p_user_id
        AND s.status IN ('trialing', 'active', 'grace_period')
        AND (s.current_period_end IS NULL OR s.current_period_end > now())
    )
    ELSE false
  END;
$function$;


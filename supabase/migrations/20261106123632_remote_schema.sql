CREATE OR REPLACE FUNCTION public.apply_position_library (
  p_roadmap_id  uuid,
  p_dance_style text
)
  RETURNS integer
  LANGUAGE plpgsql
  SET search_path TO 'public'
  AS $function$
DECLARE
  v_count integer := 0;
  v_owner uuid;
BEGIN
  SELECT user_id INTO v_owner FROM public.user_roadmaps WHERE id = p_roadmap_id;
  IF v_owner IS NULL OR v_owner <> auth.uid() THEN
    RAISE EXCEPTION 'roadmap not found';
  END IF;
  WITH ins AS (
    INSERT INTO public.video_categories (user_id, roadmap_id, name, description, system_category, position_slug, sort_order)
    SELECT auth.uid(), p_roadmap_id, t.name, t.description, false, t.slug, t.sort_order
    FROM public.position_templates t
    WHERE t.dance_style = p_dance_style AND t.active
      AND NOT EXISTS (
        SELECT 1 FROM public.video_categories c
        WHERE c.roadmap_id = p_roadmap_id AND c.user_id = auth.uid()
          AND (c.position_slug = t.slug OR lower(c.name) = lower(t.name))
      )
    RETURNING 1
  )
  SELECT count(*) INTO v_count FROM ins;
  RETURN v_count;
END;
$function$;

CREATE OR REPLACE FUNCTION public.claim_analysis_job (
  p_worker_id text
)
  RETURNS SETOF public.analysis_jobs
  LANGUAGE sql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
  UPDATE public.analysis_jobs j
  SET status = 'processing', worker_id = p_worker_id, started_at = timezone('utc'::text, now()), attempts = attempts + 1
  WHERE j.id = (
    SELECT id FROM public.analysis_jobs
    WHERE status = 'queued'
    ORDER BY created_at
    FOR UPDATE SKIP LOCKED
    LIMIT 1
  )
  RETURNING *;
$function$;

